from datetime import datetime

from pydantic import BaseModel, Field

from typing import List, Optional, Dict, Any

from contracts.enums import ColumnSemanticType

from contracts.base_artifact import BaseArtifact

class DatasetMetadata(BaseModel):
    """
    General information about the uploaded dataset.
    """

    dataset_name: str = Field(
        description="Name of the uploaded dataset"
    )

    source_type: str = Field(
        description="Source type (CSV, Excel, Database, API)"
    )

    file_name: str = Field(
        description="Original uploaded file name"
    )

    file_size_bytes: int = Field(
        description="Dataset size in bytes"
    )

    row_count: int = Field(
        description="Number of rows"
    )

    column_count: int = Field(
        description="Number of columns"
    )

    profiled_at: datetime = Field(
        default_factory=datetime.utcnow,
        description="Time when profiling was completed"
    )

class ColumnProfile(BaseModel):
    """
    Profile information for a single column.
    """

    column_name: str = Field(
        description="Column name"
    )

    data_type: str = Field(
        description="Detected data type"
    )

    nullable: bool = Field(
        description="Whether null values exist"
    )

    unique: bool = Field(
        description="Whether all values are unique"
    )

    null_count: int = Field(
        description="Number of null values"
    )

    distinct_count: int = Field(
        description="Number of distinct values"
    )

    sample_values: List[str] = Field(
        default_factory=list,
        description="Example values"
    )

    semantic_type: ColumnSemanticType = Field(
        default=ColumnSemanticType.UNKNOWN,
        description="Business meaning inferred by AI"
    )

    confidence: float = Field(
        default=0.0,
        ge=0,
        le=100,
        description="Confidence score"
    )

    recommendation: Optional[str] = Field(
        default=None,
        description="Suggested transformation"
    )

class QualityProfile(BaseModel):
    """
    Overall data quality metrics for the dataset.
    """

    quality_score: float = Field(
        ge=0,
        le=100,
        description="Overall quality score (0-100)"
    )

    duplicate_rows: int = Field(
        description="Number of duplicate rows"
    )

    duplicate_percentage: float = Field(
        ge=0,
        le=100,
        description="Percentage of duplicate rows"
    )

    total_null_values: int = Field(
        description="Total null values in the dataset"
    )

    null_percentage: float = Field(
        ge=0,
        le=100,
        description="Percentage of null values"
    )

    issues: list[str] = Field(
        default_factory=list,
        description="List of detected quality issues"
    )

class StatisticsProfile(BaseModel):
    """
    Statistical summary of the dataset.
    """

    numeric_statistics: Dict[str, Any] = Field(
        default_factory=dict,
        description="Statistics for numeric columns"
    )

    categorical_statistics: Dict[str, Any] = Field(
        default_factory=dict,
        description="Statistics for categorical columns"
    )

    date_statistics: Dict[str, Any] = Field(
        default_factory=dict,
        description="Statistics for date columns"
    )

class SemanticHint(BaseModel):
    """
    AI-generated semantic understanding of a column.
    """

    column_name: str = Field(
        description="Column name"
    )

    semantic_type: ColumnSemanticType = Field(
        description="Predicted business meaning"
    )

    confidence: float = Field(
        ge=0,
        le=100,
        description="Confidence percentage"
    )

    reasoning: str = Field(
        description="Explanation of why this semantic type was chosen"
    )

class DatasetProfile(BaseArtifact):
    """
    Complete profile of a dataset generated by the Profiler Agent.
    """

    metadata: DatasetMetadata

    columns: List[ColumnProfile]

    quality: QualityProfile

    statistics: StatisticsProfile

    semantic_hints: List[SemanticHint] = Field(
        default_factory=list
    )

    ai_summary: str = Field(
        description="Business-friendly AI summary of the dataset"
    )